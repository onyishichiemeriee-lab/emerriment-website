-- =====================================================================
-- EMerriment migration 0 — give public.leads a real primary key
-- ---------------------------------------------------------------------
-- STATUS: APPLIED to production (Supabase SQL Editor); verified 2026-11-15 by audit 02 and 03b (381/381).
-- Found in the live database (read-only audit, 2026-11-13):
--   * leads.id is bigint, NULLABLE, with NO default and NO primary key;
--     all 79 existing leads have id = NULL.
--   * Consequences: send-email claims a lead with `.eq("id", leadId)`,
--     which never matches NULL, so no report email can ever be sent;
--     tracking/unsubscribe links carry the lead id; and migration
--     20261110090400 (email_deliveries.lead_id REFERENCES leads(id))
--     cannot be created without a unique key on leads.id.
--   * Several column defaults contain literal quote characters
--     (e.g. '''pending'''), so 57 leads hold the value 'pending' WITH
--     quotes, which no code recognises.
--
-- What this does (no row is deleted; no personal field is changed)
--   1. Numbers every lead that has no id (oldest first) and adds
--      GENERATED BY DEFAULT AS IDENTITY + PRIMARY KEY on id.
--   2. Fixes the quoted defaults to the values the code uses.
--   3. Normalises the quoted state values written by those defaults:
--      'pending' -> Pending, 'New Lead' -> New Lead,
--      'Skin Quiz' -> Skin Quiz, '2.0' -> 2.0 (quotes removed only).
--
-- Must run BEFORE 20261110090400 (email_deliveries) — the filename sorts
-- first. Idempotent: every step checks the current state.
--
-- Backup: emerriment_backup.leads_20261113 is created by
-- supabase/backups/20261113_create_backup.sql before any migration.
-- Rollback: supabase/rollback/emerriment_security_rollback.sql (part 0).
-- =====================================================================

begin;

-- 1. Ids ---------------------------------------------------------------
do $$
declare
    start_at bigint;
begin
    if to_regclass('public.leads') is null then
        raise exception 'EMerriment: public.leads not found.';
    end if;

    -- Already has a primary key (e.g. re-run): nothing to number.
    if exists (select 1 from pg_constraint
               where conrelid = 'public.leads'::regclass and contype = 'p') then
        raise notice 'EMerriment: leads already has a primary key; ids left unchanged.';
        return;
    end if;

    if (select format_type(atttypid, atttypmod) from pg_attribute
        where attrelid = 'public.leads'::regclass and attname = 'id' and not attisdropped)
       not in ('bigint', 'integer') then
        raise exception 'EMerriment: leads.id is not an integer column; review before applying.';
    end if;

    -- Existing ids (none today) are kept; new numbers start above them.
    select coalesce(max(id), 0) into start_at from public.leads;

    update public.leads l
       set id = start_at + n.rn
      from (select ctid as row_ref,
                   row_number() over (order by coalesce(submitted_at, created_at) nulls last, ctid) as rn
              from public.leads
             where id is null) n
     where l.ctid = n.row_ref;

    if exists (select id from public.leads group by id having count(*) > 1) then
        raise exception 'EMerriment: duplicate lead ids exist; resolve them before adding the primary key.';
    end if;
end
$$;

do $$
begin
    if exists (select 1 from pg_constraint
               where conrelid = 'public.leads'::regclass and contype = 'p') then
        return;
    end if;

    alter table public.leads alter column id set not null;

    if (select attidentity from pg_attribute
        where attrelid = 'public.leads'::regclass and attname = 'id') = '' then
        alter table public.leads alter column id add generated by default as identity;
    end if;

    alter table public.leads add constraint leads_pkey primary key (id);

    -- The identity continues after the highest existing id.
    perform setval(pg_get_serial_sequence('public.leads', 'id'),
                   greatest((select coalesce(max(id), 0) from public.leads), 1),
                   (select count(*) > 0 from public.leads));
end
$$;


-- 2. Defaults (quotes removed) ----------------------------------------
alter table public.leads alter column quiz_version set default '2.0';
alter table public.leads alter column source       set default 'Skin Quiz';
alter table public.leads alter column status       set default 'New Lead';
alter table public.leads alter column email_status set default 'Pending';


-- 3. Values written by the quoted defaults ------------------------------
update public.leads set email_status = 'Pending'   where email_status::text = '''pending''';
update public.leads set status       = 'New Lead'  where status::text       = '''New Lead''';
update public.leads set source       = 'Skin Quiz' where source       = '''Skin Quiz''';
update public.leads set quiz_version = '2.0'       where quiz_version = '''2.0''';

comment on column public.leads.id is
    'EMerriment: identity primary key (added 2026-11-13; previously NULL for every lead).';

notify pgrst, 'reload schema';

commit;
